'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const html=fs.readFileSync('index.html','utf8'),js=fs.readFileSync('js/bt-spark.js','utf8'),sw=fs.readFileSync('sw.js','utf8'),rules=fs.readFileSync('firestore.rules','utf8');
const sprite=fs.readFileSync('images/mascot/pizza-sticker-sprite.webp');
assert.equal(sprite.toString('ascii',0,4),'RIFF');
assert.equal(sprite.toString('ascii',8,12),'WEBP');
assert.ok(sprite.length<12000,'One lightweight mascot sprite should stay under 12kB');
assert.match(html,/js\/bt-mascot-sprite\.js/);
assert.match(html,/class="pg-home-hero"/);
assert.match(html,/css\/pizza-v34\.css/);
assert.doesNotMatch(html,/id="prev-btn"/);
assert.match(js,/function statTotals\(/);
assert.match(js,/profile\?\.totalPoints\|\|0/);
assert.match(js,/pending\.filter\(e=>e\.points>0\)\.length/);
assert.match(js,/award\(entry\.points,entry\.points>0\)/);
assert.doesNotMatch(js,/Pending confirmation/);
assert.match(js,/syncIssue=syncDetail\(err\)/);
assert.match(js,/result is beyond the 72-hour sync window/);
assert.match(js,/addEventListener\('change',\(\)=>/);
assert.doesNotMatch(js,/Submit outlet request/);
assert.match(js,/pg-btn-red/);
assert.match(js,/pg-btn-green/);
assert.doesNotMatch(js,/You are excluded from player standings/);
assert.match(rules,/\(t\.dayOfWeek\(\) \+ 6\) % 7/);
assert.match(sw,/pizza-sticker-sprite\.webp/);
assert.doesNotMatch(sw,/pizza-timer\.svg/);
console.log('Mascot sprite, scoring reliability and UI regression checks passed.');
